-- Smoother Roads: places and routes on each area (view on the site, later suggest and manage).
-- Paste into the Supabase SQL Editor and run once.
-- A place is one point; a route is a start (lat, lon) and a finish (end_lat, end_lon).
-- Visitors see approved ones; the admin sees and manages everything.

create table public.area_pois (
  id         uuid primary key default gen_random_uuid(),
  area_id    text not null check (area_id ~ '^[a-z0-9-]{1,80}$'),
  kind       text not null check (kind in ('place', 'route')),
  name       text not null check (char_length(name) between 1 and 80),
  category   text check (char_length(category) <= 40),
  note       text check (char_length(note) <= 500),
  lat        double precision not null,
  lon        double precision not null,
  end_lat    double precision,
  end_lon    double precision,
  author     text not null default 'Smoother Roads',
  author_id  uuid default auth.uid() references auth.users (id) on delete set null,
  approved   boolean not null default false,
  position   integer not null default 0,
  created_at timestamptz not null default now(),
  check (kind = 'place' or (end_lat is not null and end_lon is not null))
);

create index area_pois_area on public.area_pois (area_id, position);
alter table public.area_pois enable row level security;
grant select on public.area_pois to anon, authenticated;
grant insert, update, delete on public.area_pois to authenticated;

create policy "read approved pois" on public.area_pois
  for select to anon, authenticated using (approved or public.is_admin());
create policy "admin manages pois" on public.area_pois
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

